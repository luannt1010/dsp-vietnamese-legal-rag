// Importing the existing app only exports OpenAPI; ASGI lifespan is not started.
// No model, database, server, or backend source changes are needed.
import { execFileSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import openapiTS, { astToString } from 'openapi-typescript';

const root = fileURLToPath(new URL('../../', import.meta.url));
const venvPython = path.join(
  root,
  process.platform === 'win32' ? '.venv/Scripts/python.exe' : '.venv/bin/python',
);
const python = process.env.PYTHON || (existsSync(venvPython) ? venvPython : 'python');
const document = JSON.parse(
  execFileSync(
    python,
    [
      '-c',
      'import json; from src.api.main import app; print(json.dumps(app.openapi(), ensure_ascii=True))',
    ],
    {
      cwd: root,
      encoding: 'utf8',
      env: { ...process.env, PYTHONIOENCODING: 'utf-8' },
      maxBuffer: 8 * 1024 * 1024,
    },
  ),
);

const types =
  '// Generated by npm run api:generate. Do not edit manually.\n' +
  astToString(await openapiTS(document));
// Reuse the exact backend constraints for runtime response validation too.
const definitions = JSON.parse(
  JSON.stringify(document.components.schemas).replaceAll('#/components/schemas/', '#/$defs/'),
);
const contracts =
  JSON.stringify(
    {
      $schema: 'https://json-schema.org/draft/2020-12/schema',
      $id: 'https://legal-rag.local/contracts',
      $defs: definitions,
    },
    null,
    2,
  ) + '\n';
const directory = fileURLToPath(new URL('../src/api/generated/', import.meta.url));
await mkdir(directory, { recursive: true });
for (const [name, contents] of [
  ['schema.d.ts', types],
  ['contracts.json', contracts],
]) {
  const destination = path.join(directory, name);
  if (process.argv.includes('--check')) {
    const current = await readFile(destination, 'utf8');
    if (current.replaceAll('\r\n', '\n') !== contents) {
      throw new Error(`${name} is out of date. Run npm run api:generate.`);
    }
  } else {
    await writeFile(destination, contents);
  }
}
console.log(
  process.argv.includes('--check')
    ? 'API contracts match the backend.'
    : 'Generated API types and runtime contracts.',
);
