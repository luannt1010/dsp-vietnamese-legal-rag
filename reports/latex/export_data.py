"""Export report tables/plot inputs from a frozen benchmark (standard library only).

Does not run inference, change labels, or alter the benchmark artifacts.
Run from any directory: python reports/latex/export_data.py --run RUN_DIRECTORY.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
import statistics
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]


def read(path):
    return json.loads(path.read_text(encoding="utf-8"))


def write_csv(path, rows):
    with path.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def export(run: Path):
    manifest = read(run / "manifest.json")
    report = read(run / "reports/summary.json")
    questions = manifest["identity"]["questions"]
    qrels = read(run / "qrels.json")
    out = HERE / "data"
    out.mkdir(exist_ok=True)
    # JSON is valid YAML; preserve the exact recorded matrix without inventing hardware notes.
    (HERE / "recorded-pilot.yml").write_text(json.dumps(manifest["identity"]["config"],indent=2)+"\n",encoding="utf-8")
    samples = [read(p) for p in sorted((run / "samples").glob("*/*.json"))]
    scores = [read(p) for p in sorted((run / "scores").glob("*/*.json"))]
    assert len(samples) == len(scores) == 225, "Report describes the frozen 225-sample pilot"
    rows, latency_rows, trace_rows = [], [], []
    for method, summary in report["summary"].items():
        selected = [s for s in samples if s["experiment"] == method]
        times = [s["latency_ms"] / 1000 for s in selected]
        completed = [s["latency_ms"] / 1000 for s in selected if s["result"]["status"] == "completed"]
        rows.append({"method": method, **{k.replace("@", ""): v["mean"] for k, v in summary["metrics"].items() if not k.startswith("round_")},
                     "latency": statistics.mean(times)})
        for s in selected:
            latency_rows.append({"method": method, "question": s["question_id"], "seconds": s["latency_ms"] / 1000,
                                 "status": s["result"]["status"], "rounds": len(s["result"]["rounds"])})
        trace_rows.append({"method": method, "samples": len(selected),
                           "completed": summary["statuses"].get("completed", 0),
                           "insufficient": summary["statuses"].get("insufficient_evidence", 0),
                           "judge_error_samples": summary["judge_error_samples"],
                           "rounds": sum(len(s["result"]["rounds"]) for s in selected),
                           "relation_rounds": sum(bool(r["retrieval_result"].get("relations")) for s in selected for r in s["result"]["rounds"]),
                           "relation_contexts": sum("[Quan hệ văn bản]" in (s["result"].get("context") or {}).get("context_text", "") for s in selected),
                           "completed_mean_s": statistics.mean(completed),
                           "mean_context_tokens": statistics.mean(s["context_tokens"] for s in selected)})
    write_csv(out / "metrics.csv", rows)
    write_csv(out / "latency.csv", latency_rows)
    write_csv(out / "trace-audit.csv", trace_rows)
    pairs = []
    for pair, metrics in report["comparisons"].items():
        for metric in ("ndcg@5", "factual_f1", "faithfulness"):
            p = metrics[metric]
            pairs.append({"pair": pair, "metric": metric, "n": p["n_paired_questions"], "delta": p["delta"],
                          "lower": p["ci95"][0], "upper": p["ci95"][1], "p_holm": p["p_holm"]})
    write_csv(out / "paired.csv", pairs)
    def table(name, keys, digits=4):
        lines = []
        for row in rows:
            lines.append(" & ".join([row["method"]] + [f"{row[k]:.{digits}f}" for k in keys]) + r" \\")
        (out / name).write_text("\n".join(lines) + "\n", encoding="utf-8")
    table("retrieval-table.tex", ["recall5", "precision5", "mrr5", "map5", "ndcg5", "recall20"])
    table("quality-table.tex", ["context_precision", "context_recall", "faithfulness", "factual_f1", "answer_relevancy"])
    table("factual-table.tex", ["factual_precision", "factual_recall", "factual_f1", "correct_answer_yield"])
    time_lines = []
    for row in rows:
        method = row["method"]
        timing = report["summary"][method]["timing"]["full_pipeline/completed/end_to_end_ms"]
        avg, p50, p95 = (timing[k]/1000 for k in ("mean", "p50", "p95"))
        time_lines.append(f"{method} & {row['latency']:.2f} & {avg:.2f} & {p50:.2f} & {p95:.2f}" + r" \\")
    (out / "latency-table.tex").write_text("\n".join(time_lines)+"\n",encoding="utf-8")
    # Confidence interval plot uses the paired distribution already generated by the benchmark.
    ci = [r for r in pairs if r["metric"] == "ndcg@5" and r["pair"].endswith("-B0")]
    # Write straightforward explicit asymmetric bars to avoid PGF table dependencies.
    (out / "ci-plot.tex").write_text("\n".join(
        rf"\addplot[navy,thick] coordinates {{({r['lower']},{i}) ({r['upper']},{i})}};\addplot[only marks,mark=*,navy] coordinates {{({r['delta']},{i})}};"
        for i,r in enumerate(ci,1)),encoding="utf-8")
    # Empirical cumulative distributions show all statuses without smoothing.
    ecdf = []
    colors = ["navy", "orange", "teal", "purple", "black"]
    for row,color in zip(rows,colors):
        vals = sorted(s["latency_ms"]/1000 for s in samples if s["experiment"]==row["method"])
        coords=" ".join(f"({v:.5f},{(i+1)/len(vals):.6f})" for i,v in enumerate(vals))
        ecdf.append(rf"\addplot+[const plot,mark=none,thick,color={color}] coordinates {{{coords}}};\addlegendentry{{{row['method']}}}")
    (out / "ecdf-plot.tex").write_text("\n".join(ecdf),encoding="utf-8")
    evidence = {
        "run": run.name, "manifest_fingerprint": report["manifest_fingerprint"],
        "questions": len(questions), "topics": dict(Counter(q["topic"] for q in questions)),
        "types": dict(Counter(q["question_type"] for q in questions)),
        "qrels_cardinality": dict(Counter(len(ids) for ids in qrels["labels"].values())),
        "holm_family_tests": sum(v.get("p_value") is not None for metrics in report["comparisons"].values() for v in metrics.values()),
        "all_p_holm_ge_005": all(v["p_holm"] >= .05 for metrics in report["comparisons"].values() for v in metrics.values()),
        "b3_b4_identical_answers": sum(
            next(x for x in samples if x["experiment"]=="B3" and x["question_id"]==s["question_id"])["result"]["answer"] == s["result"]["answer"]
            for s in samples if s["experiment"]=="B4"),
        "input_sha256": {str(p.relative_to(run)):hashlib.sha256(p.read_bytes()).hexdigest()
                         for p in [run/"manifest.json",run/"qrels.json",run/"reports/summary.json",run/"reports/summary.csv",run/"reports/latency.csv"]},
        "denominators": {m:{k:v["n_questions"] for k,v in s["metrics"].items() if not k.startswith("round_")} for m,s in report["summary"].items()},
    }
    (out / "provenance.json").write_text(json.dumps(evidence,ensure_ascii=False,indent=2)+"\n",encoding="utf-8")
    print(f"Exported {len(rows)} configurations, {len(samples)} traces; source artifacts unchanged.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run", type=Path, default=ROOT/".runtime/benchmarks/three-topics-dev-v1-fixed-01")
    export(parser.parse_args().run.resolve())
